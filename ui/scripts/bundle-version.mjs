// The wallet bundle is served from a fixed path with
// "cache-control: public, max-age=31536000, immutable", so browsers and
// Cloudflare keep an old copy for a year. The controller loads it as
// `<path>?v=<content hash>` instead: the hash lives in a committed module
// that the build rewrites (vite.config.ts) and check-bundle.mjs verifies.
// Discourse serves the file whatever the query string is.
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

/** Where Discourse serves public/javascripts/siwe.iife.js. */
export const BUNDLE_URL_PATH =
  '/plugins/discourse-siwe-auth/javascripts/siwe.iife.js'

/** The committed bundle. */
export const BUNDLE_FILE = fileURLToPath(
  new URL('../../public/javascripts/siwe.iife.js', import.meta.url),
)

/** The committed module the controller imports the versioned URL from. */
export const VERSION_MODULE_FILE = fileURLToPath(
  new URL(
    '../../assets/javascripts/discourse/lib/siwe-bundle-version.js',
    import.meta.url,
  ),
)

/** First 16 hex digits of the SHA-256 of the bundle's bytes. */
export function bundleVersion(contents) {
  return createHash('sha256').update(contents).digest('hex').slice(0, 16)
}

/** The text of assets/javascripts/discourse/lib/siwe-bundle-version.js. */
export function versionModule(version) {
  return `// Generated by ui/vite.config.ts from public/javascripts/siwe.iife.js: do not edit.
// The hash changes the URL whenever the bundle changes, so browsers and the CDN
// fetch the new bundle instead of a cached one (it is served as immutable).
// ui/scripts/check-bundle.mjs fails when it does not match the bundle.
export const SIWE_BUNDLE_VERSION = '${version}'

export const SIWE_BUNDLE_URL = \`${BUNDLE_URL_PATH}?v=\${SIWE_BUNDLE_VERSION}\`
`
}

/** The version in the committed module, or null when it has none. */
export function committedVersion(file = VERSION_MODULE_FILE) {
  const text = readFileSync(file, 'utf8')
  return text.match(/SIWE_BUNDLE_VERSION = '([0-9a-f]+)'/)?.[1] ?? null
}
